"""Instant Workspace Snapshot & Rollback Manager (100% Python stdlib, MIT clean-room).

Provides lightweight, per-file pre-edit safety checkpoints stored inside
`<repo_root>/.vieforge/snapshots/<snapshot_id>/` so any risky refactor or repair
attempt can be rolled back in one command — even outside a Git repository.

Safety guarantees:
  - Strict repo-root containment (blocks path traversal outside `repo_root`).
  - Records both existing files (with SHA-256 integrity checks) and non-existent
    target paths (so rollback cleanly removes newly created stray files).
  - Auto-writes `.vieforge/snapshots/.gitignore` (`*`) to prevent accidental commits.
"""

from __future__ import annotations

import difflib
import hashlib
import json
import shutil
import uuid
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from core.concurrency import atomic_write_json


@dataclass
class SnapshotFileEntry:
    rel_path: str
    existed: bool
    sha256: str = ""
    size_bytes: int = 0
    backup_relpath: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class SnapshotRecord:
    snapshot_id: str
    created_at: str
    label: str
    note: str
    files: list[SnapshotFileEntry] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "snapshot_id": self.snapshot_id,
            "created_at": self.created_at,
            "label": self.label,
            "note": self.note,
            "file_count": len(self.files),
            "files": [f.to_dict() for f in self.files],
            "metadata": self.metadata,
        }


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


class WorkspaceSnapshotManager:
    """Create, diff, rollback, and prune lightweight source-file checkpoints."""

    def __init__(
        self,
        repo_root: Path | str = ".",
        snapshots_dir: Path | str | None = None,
    ) -> None:
        self.repo_root = Path(repo_root).resolve()
        self.snapshots_dir = (
            Path(snapshots_dir).resolve()
            if snapshots_dir is not None
            else (self.repo_root / ".vieforge" / "snapshots")
        )

    def _ensure_storage_dir(self) -> None:
        self.snapshots_dir.mkdir(parents=True, exist_ok=True)
        gitignore = self.snapshots_dir / ".gitignore"
        if not gitignore.exists():
            gitignore.write_text("# Auto-generated by VieForge snapshots\n*\n", encoding="utf-8")

    def _resolve_contained(self, target: Path | str) -> tuple[Path, str]:
        """Resolve `target` and verify it remains strictly inside `self.repo_root`."""
        p = Path(target)
        abs_path = p.resolve() if p.is_absolute() else (self.repo_root / p).resolve()
        try:
            rel = abs_path.relative_to(self.repo_root)
        except ValueError as exc:
            raise ValueError(
                f"Snapshot path escapes repo root ({self.repo_root}): {target}"
            ) from exc
        rel_str = str(rel).replace("\\", "/")
        if not rel_str or rel_str == ".":
            raise ValueError("Cannot snapshot repository root directory directly; pass file paths.")
        return abs_path, rel_str

    def create_snapshot(
        self,
        files: list[Path | str],
        *,
        label: str = "manual",
        note: str = "",
        metadata: dict[str, Any] | None = None,
    ) -> SnapshotRecord:
        """Capture an atomic backup of `files` before applying edits or repair loops."""
        if not files:
            raise ValueError("Provide at least one file path to snapshot.")
        self._ensure_storage_dir()

        ts = datetime.now(timezone.utc)
        safe_label = "".join(ch if ch.isalnum() or ch in ("-", "_") else "_" for ch in label.strip())[:24] or "snap"
        snap_id = f"{ts.strftime('%Y%m%dT%H%M%SZ')}_{safe_label}_{uuid.uuid4().hex[:6]}"
        snap_dir = self.snapshots_dir / snap_id
        payload_dir = snap_dir / "files"
        payload_dir.mkdir(parents=True, exist_ok=True)

        entries: list[SnapshotFileEntry] = []
        seen_rel: set[str] = set()
        for raw_target in files:
            abs_path, rel_str = self._resolve_contained(raw_target)
            if rel_str in seen_rel:
                continue
            seen_rel.add(rel_str)

            if abs_path.is_file():
                raw_bytes = abs_path.read_bytes()
                backup_rel = f"files/{rel_str}"
                dest = snap_dir / backup_rel
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(raw_bytes)
                entries.append(
                    SnapshotFileEntry(
                        rel_path=rel_str,
                        existed=True,
                        sha256=_sha256_bytes(raw_bytes),
                        size_bytes=len(raw_bytes),
                        backup_relpath=backup_rel,
                    )
                )
            elif not abs_path.exists():
                entries.append(
                    SnapshotFileEntry(
                        rel_path=rel_str,
                        existed=False,
                    )
                )
            else:
                raise ValueError(f"Snapshot target is a directory, expected a file: {rel_str}")

        record = SnapshotRecord(
            snapshot_id=snap_id,
            created_at=ts.isoformat(),
            label=label.strip() or "manual",
            note=note.strip(),
            files=entries,
            metadata=dict(metadata or {}),
        )
        atomic_write_json(snap_dir / "manifest.json", record.to_dict())
        return record

    def _load_manifest(self, snapshot_id: str) -> SnapshotRecord:
        manifest_path = self.snapshots_dir / snapshot_id / "manifest.json"
        if not manifest_path.is_file():
            raise FileNotFoundError(f"Snapshot not found: {snapshot_id}")
        raw = json.loads(manifest_path.read_text(encoding="utf-8"))
        entries = [
            SnapshotFileEntry(
                rel_path=f["rel_path"],
                existed=bool(f["existed"]),
                sha256=str(f.get("sha256", "")),
                size_bytes=int(f.get("size_bytes", 0)),
                backup_relpath=str(f.get("backup_relpath", "")),
            )
            for f in raw.get("files", [])
        ]
        return SnapshotRecord(
            snapshot_id=str(raw["snapshot_id"]),
            created_at=str(raw["created_at"]),
            label=str(raw.get("label", "")),
            note=str(raw.get("note", "")),
            files=entries,
            metadata=dict(raw.get("metadata", {})),
        )

    def list_snapshots(self, limit: int = 20) -> list[SnapshotRecord]:
        """Return newest-first snapshot manifests."""
        if not self.snapshots_dir.is_dir():
            return []
        records: list[SnapshotRecord] = []
        for child in self.snapshots_dir.iterdir():
            if not child.is_dir():
                continue
            manifest = child / "manifest.json"
            if not manifest.is_file():
                continue
            try:
                records.append(self._load_manifest(child.name))
            except (OSError, ValueError, KeyError):
                continue
        records.sort(key=lambda r: r.created_at, reverse=True)
        return records[: max(1, limit)]

    def _resolve_snapshot_id(self, snapshot_id: str | None) -> str:
        if snapshot_id:
            return snapshot_id
        snaps = self.list_snapshots(limit=1)
        if not snaps:
            raise FileNotFoundError("No workspace snapshots exist yet.")
        return snaps[0].snapshot_id

    def diff_snapshot(self, snapshot_id: str | None = None) -> dict[str, Any]:
        """Compare current workspace files against a snapshot using unified diff."""
        sid = self._resolve_snapshot_id(snapshot_id)
        record = self._load_manifest(sid)
        snap_dir = self.snapshots_dir / sid

        diffs: list[dict[str, Any]] = []
        for entry in record.files:
            live_path, _ = self._resolve_contained(entry.rel_path)
            if entry.existed:
                backup_path = snap_dir / entry.backup_relpath
                before_text = backup_path.read_text(encoding="utf-8", errors="replace").splitlines()
                if live_path.is_file():
                    after_text = live_path.read_text(encoding="utf-8", errors="replace").splitlines()
                    status = "unchanged" if before_text == after_text else "modified"
                else:
                    after_text = []
                    status = "deleted_since_snapshot"
            else:
                before_text = []
                if live_path.is_file():
                    after_text = live_path.read_text(encoding="utf-8", errors="replace").splitlines()
                    status = "created_since_snapshot"
                else:
                    after_text = []
                    status = "unchanged"

            patch_lines = list(
                difflib.unified_diff(
                    before_text,
                    after_text,
                    fromfile=f"snapshot/{entry.rel_path}",
                    tofile=f"workspace/{entry.rel_path}",
                    lineterm="",
                )
            )
            diffs.append(
                {
                    "rel_path": entry.rel_path,
                    "status": status,
                    "unified_diff": "\n".join(patch_lines),
                }
            )
        return {"snapshot_id": sid, "label": record.label, "files": diffs}

    def rollback(
        self,
        snapshot_id: str | None = None,
        *,
        dry_run: bool = False,
    ) -> dict[str, Any]:
        """Restore tracked files to the exact state stored in `snapshot_id`."""
        sid = self._resolve_snapshot_id(snapshot_id)
        record = self._load_manifest(sid)
        snap_dir = self.snapshots_dir / sid

        restored: list[str] = []
        removed: list[str] = []
        unchanged: list[str] = []

        for entry in record.files:
            live_path, _ = self._resolve_contained(entry.rel_path)
            if entry.existed:
                backup_path = snap_dir / entry.backup_relpath
                if not backup_path.is_file():
                    raise FileNotFoundError(f"Backup payload missing for {entry.rel_path} in {sid}")
                data = backup_path.read_bytes()
                if entry.sha256 and _sha256_bytes(data) != entry.sha256:
                    raise ValueError(f"Snapshot integrity mismatch (SHA-256) for {entry.rel_path}")
                if live_path.is_file() and _sha256_bytes(live_path.read_bytes()) == entry.sha256:
                    unchanged.append(entry.rel_path)
                    continue
                if not dry_run:
                    live_path.parent.mkdir(parents=True, exist_ok=True)
                    live_path.write_bytes(data)
                restored.append(entry.rel_path)
            else:
                if live_path.is_file():
                    if not dry_run:
                        live_path.unlink()
                    removed.append(entry.rel_path)
                else:
                    unchanged.append(entry.rel_path)

        return {
            "snapshot_id": sid,
            "label": record.label,
            "dry_run": dry_run,
            "restored": restored,
            "removed": removed,
            "unchanged": unchanged,
        }

    def prune(self, keep: int = 20) -> int:
        """Delete oldest snapshots beyond `keep` and return count removed."""
        all_snaps = self.list_snapshots(limit=10_000)
        to_delete = all_snaps[max(0, keep) :]
        removed = 0
        for rec in to_delete:
            target_dir = self.snapshots_dir / rec.snapshot_id
            if target_dir.is_dir():
                shutil.rmtree(target_dir, ignore_errors=True)
                removed += 1
        return removed
