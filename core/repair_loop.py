"""Approval-Gated Repair Loop with Anti-Loop Fingerprinting & Auto-Rollback (100% stdlib, MIT).

Enforces strict human-in-the-loop governance for every source-code repair:
  Phase 1 (`propose_repair`):
    - Compresses logs + locates exact failing symbols via `fault_locator`.
    - Queries project-local `ErrorMemory` (< 5 ms) for verified past fixes.
    - Detects repeated error fingerprints (Anti-Loop) and enforces `max_attempts`.
    - Pre-validates narrow SEARCH/REPLACE edits in RAM (zero disk writes) and saves
      the proposal in `AWAITING_APPROVAL` state with full unified diff preview.
  Phase 2 (`approve_and_apply`):
    - Requires explicit proposal ID approval (raises `ApprovalRequiredError` otherwise).
    - Captures an instant pre-edit `WorkspaceSnapshotManager` checkpoint.
    - Applies the syntax-verified patch and runs the optional verification command.
    - On verification PASS: marks `APPROVED_AND_FIXED` and records the verified fix into
      `ErrorMemory` for instant $0 recall next time.
    - On verification FAIL: automatically rolls back to the pre-edit snapshot and logs the
      disproven hypothesis so the agent never repeats a failed idea.
"""

from __future__ import annotations

import json
import os
import shlex
import uuid
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from core.concurrency import atomic_write_json
from core.error_memory import ErrorMemory
from core.fault_locator import locate_fault
from core.impact_guard import assess_impact
from core.output_trimmer import trim_output
from core.safe_patcher import PatchApplier, PatchEdit, parse_search_replace_blocks
from core.subprocess_runner import run_isolated
from core.workspace_snapshot import WorkspaceSnapshotManager


class ApprovalRequiredError(RuntimeError):
    """Raised when an operation attempts to apply edits without explicit human approval."""


@dataclass
class RepairProposal:
    proposal_id: str
    attempt_no: int
    created_at: str
    fingerprint: str
    error_type: str
    error_message: str
    hypothesis: str
    status: str  # AWAITING_APPROVAL | DIAGNOSIS_ONLY | INVALID_PATCH | LOOP_DETECTED | MAX_ATTEMPTS_REACHED | APPROVED_AND_FIXED | ROLLED_BACK_ON_FAIL | REJECTED
    loop_detected: bool = False
    edits: list[dict[str, Any]] = field(default_factory=list)
    preview_diffs: list[dict[str, Any]] = field(default_factory=list)
    known_fixes: list[dict[str, Any]] = field(default_factory=list)
    fault_brief_md: str = ""
    impact_risk: str = "GREEN"
    impact_related_tests: list[str] = field(default_factory=list)
    impact_summary: str = ""
    snapshot_id: str = ""
    approved_by: str = ""
    rejected_reason: str = ""
    verification_rc: int | None = None
    verification_output: str = ""
    post_fingerprint: str = ""
    resolved_at: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


class RepairLoopManager:
    """Two-phase approval-gated debugging & repair coordinator."""

    def __init__(
        self,
        repo_root: Path | str = ".",
        *,
        sessions_dir: Path | str | None = None,
        memory_db_path: Path | str | None = None,
        max_attempts: int = 3,
    ) -> None:
        self.repo_root = Path(repo_root).resolve()
        self.sessions_dir = (
            Path(sessions_dir).resolve()
            if sessions_dir is not None
            else (self.repo_root / ".vieforge" / "repair_sessions")
        )
        self.memory_db_path = (
            Path(memory_db_path).resolve()
            if memory_db_path is not None
            else (self.repo_root / ".vieforge" / "error_memory.db")
        )
        self.max_attempts = max(1, int(max_attempts))
        self.snapshots = WorkspaceSnapshotManager(self.repo_root)
        self.applier = PatchApplier(self.repo_root)

    def _ensure_dirs(self) -> None:
        self.sessions_dir.mkdir(parents=True, exist_ok=True)
        gitignore = self.sessions_dir / ".gitignore"
        if not gitignore.exists():
            gitignore.write_text("# Auto-generated by VieForge repair sessions\n*\n", encoding="utf-8")

    def _session_path(self, session_id: str) -> Path:
        safe = "".join(ch if ch.isalnum() or ch in ("-", "_") else "_" for ch in session_id.strip())
        if not safe:
            raise ValueError("session_id must not be empty")
        return self.sessions_dir / f"{safe}.json"

    def _load_or_init_session(self, session_id: str) -> dict[str, Any]:
        path = self._session_path(session_id)
        if path.is_file():
            return dict(json.loads(path.read_text(encoding="utf-8")))
        return {
            "session_id": session_id,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "max_attempts": self.max_attempts,
            "seen_fingerprints": [],
            "rejected_hypotheses": [],
            "proposals": [],
        }

    def _save_session(self, session: dict[str, Any]) -> None:
        self._ensure_dirs()
        atomic_write_json(self._session_path(session["session_id"]), session)

    def get_session(self, session_id: str) -> dict[str, Any]:
        path = self._session_path(session_id)
        if not path.is_file():
            raise FileNotFoundError(f"Repair session not found: {session_id}")
        return dict(json.loads(path.read_text(encoding="utf-8")))

    def list_sessions(self, limit: int = 20) -> list[dict[str, Any]]:
        if not self.sessions_dir.is_dir():
            return []
        sessions: list[dict[str, Any]] = []
        for p in self.sessions_dir.glob("*.json"):
            try:
                data = json.loads(p.read_text(encoding="utf-8"))
                sessions.append(
                    {
                        "session_id": data.get("session_id", p.stem),
                        "created_at": data.get("created_at", ""),
                        "proposal_count": len(data.get("proposals", [])),
                        "last_status": (
                            data["proposals"][-1]["status"] if data.get("proposals") else "EMPTY"
                        ),
                    }
                )
            except (OSError, ValueError):
                continue
        sessions.sort(key=lambda s: s["created_at"], reverse=True)
        return sessions[: max(1, limit)]

    def propose_repair(
        self,
        *,
        session_id: str,
        log_text: str,
        hypothesis: str = "",
        edits: list[PatchEdit] | None = None,
        patch_text: str = "",
        include_git: bool = True,
    ) -> RepairProposal:
        """Phase 1: Diagnose, check ErrorMemory & Anti-Loop, preview diffs. NEVER writes repo files."""
        session = self._load_or_init_session(session_id)
        proposals: list[dict[str, Any]] = list(session.get("proposals", []))
        attempt_no = len(proposals) + 1

        report = locate_fault(log_text, repo_root=self.repo_root, include_git=include_git)
        with ErrorMemory(self.memory_db_path) as mem:
            known = [
                m.to_dict()
                for m in mem.lookup(
                    fingerprint=report.fingerprint,
                    error_type=report.error_type,
                    query_text=f"{report.error_message} {' '.join(s.file_path for s in report.located_symbols)}",
                    limit=3,
                )
            ]

        seen_fps: list[str] = list(session.get("seen_fingerprints", []))
        loop_detected = report.fingerprint in seen_fps
        if not loop_detected:
            seen_fps.append(report.fingerprint)

        resolved_edits = list(edits or [])
        if patch_text.strip():
            resolved_edits.extend(parse_search_replace_blocks(patch_text))

        prop_id = f"prop_{attempt_no}_{uuid.uuid4().hex[:6]}"
        now = datetime.now(timezone.utc).isoformat()
        preview_diffs: list[dict[str, Any]] = []
        status = "DIAGNOSIS_ONLY"
        reason = ""
        impact_risk = "GREEN"
        impact_related_tests: list[str] = []
        impact_summary = ""

        if resolved_edits:
            touched = sorted({e.file_path for e in resolved_edits})
            imp = assess_impact(self.repo_root, touched)
            impact_risk = imp.risk_level
            impact_related_tests = imp.related_tests
            impact_summary = "; ".join(imp.reasons)

        if attempt_no > self.max_attempts:
            status = "MAX_ATTEMPTS_REACHED"
            reason = f"Reached max_attempts={self.max_attempts}; escalate to human review."
        elif loop_detected and resolved_edits:
            status = "LOOP_DETECTED"
            reason = (
                f"Fingerprint {report.fingerprint} already seen in this session; "
                "rethink root cause before proposing another patch."
            )
        elif resolved_edits:
            dry = self.applier.apply(resolved_edits, dry_run=True)
            preview_diffs = [r.to_dict() for r in dry.results]
            if dry.ok:
                status = "AWAITING_APPROVAL"
            else:
                status = "INVALID_PATCH"
                reason = dry.error

        proposal = RepairProposal(
            proposal_id=prop_id,
            attempt_no=attempt_no,
            created_at=now,
            fingerprint=report.fingerprint,
            error_type=report.error_type,
            error_message=report.error_message,
            hypothesis=hypothesis.strip(),
            status=status,
            loop_detected=loop_detected,
            edits=[e.to_dict() for e in resolved_edits],
            preview_diffs=preview_diffs,
            known_fixes=known,
            fault_brief_md=report.to_markdown(),
            impact_risk=impact_risk,
            impact_related_tests=impact_related_tests,
            impact_summary=impact_summary,
            rejected_reason=reason,
        )
        proposals.append(proposal.to_dict())
        session["seen_fingerprints"] = seen_fps
        session["proposals"] = proposals
        self._save_session(session)
        return proposal

    def approve_and_apply(
        self,
        *,
        session_id: str,
        proposal_id: str,
        approved_by: str = "user",
        verify_cmd: str = "",
        auto_rollback_on_fail: bool = True,
        record_to_memory: bool = True,
        prevention: str = "",
        timeout_sec: float = 120.0,
    ) -> RepairProposal:
        """Phase 2: Execute an explicitly approved proposal with snapshot + verify + auto-rollback."""
        if not approved_by or not approved_by.strip():
            raise ApprovalRequiredError("Explicit approver identity is required before applying a patch.")

        session = self.get_session(session_id)
        target_idx = -1
        for idx, item in enumerate(session.get("proposals", [])):
            if item.get("proposal_id") == proposal_id:
                target_idx = idx
                break
        if target_idx < 0:
            raise FileNotFoundError(f"Proposal {proposal_id} not found in session {session_id}")

        raw = session["proposals"][target_idx]
        if raw.get("status") != "AWAITING_APPROVAL":
            raise ApprovalRequiredError(
                f"Proposal {proposal_id} is not awaiting approval (current status: {raw.get('status')})."
            )

        edits = [
            PatchEdit(file_path=e["file_path"], search=e["search"], replace=e["replace"])
            for e in raw.get("edits", [])
        ]
        if not edits:
            raise ApprovalRequiredError(f"Proposal {proposal_id} contains no patch edits to apply.")

        # 1. Always capture a safety snapshot before mutating any workspace file
        target_files = sorted({e.file_path for e in edits})
        snap = self.snapshots.create_snapshot(
            target_files,
            label=f"repair_{proposal_id}",
            note=f"Pre-apply snapshot for {session_id}/{proposal_id} approved by {approved_by}",
        )
        raw["snapshot_id"] = snap.snapshot_id
        raw["approved_by"] = approved_by.strip()

        # 2. Apply validated narrow edits
        apply_res = self.applier.apply(edits, dry_run=False)
        if not apply_res.ok:
            self.snapshots.rollback(snap.snapshot_id, dry_run=False)
            raw["status"] = "INVALID_PATCH"
            raw["rejected_reason"] = apply_res.error
            raw["resolved_at"] = datetime.now(timezone.utc).isoformat()
            self._save_session(session)
            return RepairProposal(**raw)

        # 3. Run regression verification command when supplied
        if verify_cmd.strip():
            raw_parts = shlex.split(verify_cmd, posix=(os.name != "nt"))
            parts = [
                p[1:-1] if len(p) >= 2 and p[0] == p[-1] and p[0] in ('"', "'") else p
                for p in raw_parts
            ]
            v_res = run_isolated(
                parts,
                cwd=str(self.repo_root),
                timeout_sec=timeout_sec,
                max_output_lines=80,
            )
            raw["verification_rc"] = v_res.returncode
            combined_out = "\n".join(p for p in (v_res.stdout_trimmed, v_res.stderr_trimmed) if p)
            raw["verification_output"] = trim_output(combined_out, max_lines=40).text

            if v_res.returncode == 0:
                raw["status"] = "APPROVED_AND_FIXED"
                if record_to_memory:
                    with ErrorMemory(self.memory_db_path) as mem:
                        mem.record_incident(
                            fingerprint=raw["fingerprint"],
                            error_type=raw["error_type"],
                            symptom=raw["error_message"],
                            root_cause=raw["hypothesis"] or "Verified approved repair",
                            verified_fix=f"Approved patch ({proposal_id}) on {', '.join(target_files)}",
                            prevention=prevention or f"Verified via: {verify_cmd}",
                            files=target_files,
                        )
            else:
                post_report = locate_fault(
                    combined_out,
                    repo_root=self.repo_root,
                    include_git=False,
                    include_callers=False,
                )
                raw["post_fingerprint"] = post_report.fingerprint
                if auto_rollback_on_fail:
                    self.snapshots.rollback(snap.snapshot_id, dry_run=False)
                    raw["status"] = "ROLLED_BACK_ON_FAIL"
                    session.setdefault("rejected_hypotheses", []).append(
                        {
                            "proposal_id": proposal_id,
                            "hypothesis": raw.get("hypothesis", ""),
                            "before_fp": raw.get("fingerprint", ""),
                            "after_fp": post_report.fingerprint,
                            "same_error_loop": post_report.fingerprint == raw.get("fingerprint", ""),
                        }
                    )
                else:
                    raw["status"] = "VERIFICATION_FAILED"
        else:
            raw["status"] = "APPROVED_AND_FIXED"

        raw["resolved_at"] = datetime.now(timezone.utc).isoformat()
        self._save_session(session)
        return RepairProposal(**raw)

    def reject_proposal(
        self,
        *,
        session_id: str,
        proposal_id: str,
        reason: str = "Rejected by reviewer",
    ) -> RepairProposal:
        """Explicitly reject a pending repair proposal without touching any source files."""
        session = self.get_session(session_id)
        for item in session.get("proposals", []):
            if item.get("proposal_id") == proposal_id:
                item["status"] = "REJECTED"
                item["rejected_reason"] = reason.strip() or "Rejected by reviewer"
                item["resolved_at"] = datetime.now(timezone.utc).isoformat()
                session.setdefault("rejected_hypotheses", []).append(
                    {
                        "proposal_id": proposal_id,
                        "hypothesis": item.get("hypothesis", ""),
                        "reason": item["rejected_reason"],
                    }
                )
                self._save_session(session)
                return RepairProposal(**item)
        raise FileNotFoundError(f"Proposal {proposal_id} not found in session {session_id}")
